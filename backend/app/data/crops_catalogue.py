def get_crop_requirement(crop_id: str) -> Optional[CropRequirement]:
    """Retrieve verified crop requirements specification with alias tolerance."""
    if not crop_id:
        return None
    cid = crop_id.strip().lower()
    canonical_id = CROP_ALIASES.get(cid, cid)
    return RAW_CROPS.get(canonical_id)


def list_supported_crops(
    season: Optional[CropSeason] = None,
    category: Optional[str] = None,
    search: Optional[str] = None,
) -> List[CropRequirement]:
    """List supported crops, with optional season, category, and search query filters."""
    crops = list(RAW_CROPS.values())

    if season:
        crops = [c for c in crops if c.season == season or c.season == CropSeason.PERENNIAL]

    if category:
        cat_clean = category.strip().lower()
        crops = [c for c in crops if c.crop_category.lower() == cat_clean]

    if search:
        q = search.strip().lower()
        crops = [
            c for c in crops
            if q in c.crop_id.lower()
            or q in c.name.lower()
            or q in c.name_mr.lower()
            or q in c.scientific_name.lower()
            or any(q in v.lower() for v in c.recommended_varieties)
        ]

    return crops
