def get_regional_soil_profile(block_id: str) -> RegionalSoilSummaryResponse:
    """Retrieve verified regional soil profile for an administrative block."""
    raw = RAW_REGIONAL_SOIL.get(block_id.strip().lower())
    if not raw:
        # Default representative semi-arid Vertisol for fallback
        return RegionalSoilSummaryResponse(
            location_id=block_id,
            location_name=block_id.capitalize(),
            district_name="Maharashtra",
            source=SoilDataSource.REGIONAL_ESTIMATE,
            dataset_name="ICAR-NBSS&LUP Regional Generalised Vertisol Benchmark",
            spatial_resolution="Regional series generalization",
            depth_layer="0-30cm",
            dominant_texture=SoilTextureClass.BLACK_COTTON_VERTISOL,
            clay_fraction_pct=45.0,
            sand_fraction_pct=25.0,
            silt_fraction_pct=30.0,
            topsoil_ph=7.8,
            organic_carbon_pct=0.45,
            cation_exchange_capacity=40.0,
            available_water_capacity_mm_m=140.0,
            drainage_class="moderately_drained",
            uncertainty_note="Broad Deccan plateau Vertisol baseline; site-specific calibration pending.",
            retrieved_at=datetime.now(timezone.utc),
        )

    return RegionalSoilSummaryResponse(
        location_id=raw["location_id"],
        location_name=raw["location_name"],
        district_name=raw["district_name"],
        source=raw["source"],
        dataset_name=raw["dataset_name"],
        spatial_resolution=raw["spatial_resolution"],
        depth_layer=raw["depth_layer"],
        dominant_texture=raw["dominant_texture"],
        clay_fraction_pct=raw["clay_fraction_pct"],
        sand_fraction_pct=raw["sand_fraction_pct"],
        silt_fraction_pct=raw["silt_fraction_pct"],
        topsoil_ph=raw["topsoil_ph"],
        organic_carbon_pct=raw["organic_carbon_pct"],
        cation_exchange_capacity=raw["cation_exchange_capacity"],
        available_water_capacity_mm_m=raw["available_water_capacity_mm_m"],
        drainage_class=raw["drainage_class"],
        uncertainty_note=raw["uncertainty_note"],
        retrieved_at=datetime.now(timezone.utc),
    )
